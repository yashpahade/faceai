"""Alembic migrations == ORM models (koi model change bina migration ke merge na ho)."""

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from faceai.attendance.migrate import alembic_config


def test_upgrade_head_matches_models(tmp_path):
    cfg = alembic_config(f"sqlite:///{(tmp_path / 'm.db').as_posix()}")
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)  # models vs migrated DB: koi diff => fail
    except AutogenerateDiffsDetected as e:  # pragma: no cover - message is the useful part
        raise AssertionError(f"models changed without a migration: {e}") from None
